// Writes MANIFEST.md listing the rendered files in out/ (they stay out of git).
const { execFileSync } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const out = path.join(root, 'out');
const files = fs.existsSync(out) ? fs.readdirSync(out).filter(f => f.endsWith('.mp4')).sort() : [];
const RATIO = { '1080x1920': '9:16', '1080x1080': '1:1', '1920x1080': '16:9' };

const rows = files.map(f => {
  const p = path.join(out, f);
  const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-print_format', 'json', '-show_format', '-show_streams', p]));
  const v = probe.streams.find(s => s.codec_type === 'video');
  const size = `${v.width}x${v.height}`;
  const sha = crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex').slice(0, 16);
  const mb = (fs.statSync(p).size / 1e6).toFixed(1);
  const audio = f.endsWith('-vo.mp4') ? 'voiceover + music' : 'music only';
  return `| \`${f}\` | ${RATIO[size] || size} | ${(+probe.format.duration).toFixed(1)} s | ${mb} MB | ${audio} | \`${sha}\` |`;
});

fs.writeFileSync(path.join(root, 'MANIFEST.md'), `# Rendered files

Generated by \`render/make.sh\`. The MP4s live in \`marketing/out/\` and are not committed.
All are H.264 High + AAC 48 kHz, 30 fps, captions burned in.

| File | Ratio | Length | Size | Audio | SHA-256 (first 16) |
|---|---|---|---|---|---|
${rows.join('\n')}
`);
console.log(`MANIFEST.md: ${files.length} files`);
